#!/usr/bin/env python3
"""Adapter: decode liblzma streams whose sizes straddle the size-field split.

Called by the generic acceptance audit. This is the project-specific half of
the "取边界要按字段宽度，而不是按习惯" rule.

MoonXZ's bug was in an 18-bit length field stored as 5 bits in a control byte
plus a 16-bit low half, holding `size - 1`. It broke whenever the low half was
0xFFFF - that is, whenever the size was **not** a multiple of 65536. A test that
only used 64 KiB sat exactly on the boundary that does not trigger it.

So the sizes below deliberately include non-multiples above 64 KiB, generated by
liblzma rather than by MoonXZ. Testing with our own encoder would never reach
this path, because our encoder caps chunks at 64 KiB.

Exit 0 if every stream decodes to the exact original bytes.
"""

from __future__ import annotations

import lzma
import subprocess
import sys
import tempfile
from pathlib import Path

# The boundary that matters is 65536, not 1024: the low half is 16 bits.
SIZES = [0, 1, 65535, 65536, 65537, 131071, 131072, 131073, 262144, 1048576]


def main() -> int:
    root = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
    failures: list[str] = []

    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        for size in SIZES:
            # Incompressible data keeps liblzma from merging chunks, so the
            # declared size survives to the decoder unchanged.
            payload = bytes((i * 7 + 13) % 251 for i in range(size))
            encoded = lzma.compress(payload, format=lzma.FORMAT_XZ, preset=6)

            src = work / f"b{size}.xz"
            dst = work / f"b{size}.out"
            src.write_bytes(encoded)

            proc = subprocess.run(
                ["moon", "run", "-q", "cmd/main", "--",
                 "decompress-file", str(src), str(dst)],
                cwd=root, capture_output=True, text=True,
                encoding="utf-8", errors="replace",
            )
            if proc.returncode != 0:
                detail = ((proc.stdout or "") + (proc.stderr or "")).strip()[:90]
                failures.append(f"{size}: {detail or 'nonzero exit'}")
                continue
            if not dst.exists():
                failures.append(f"{size}: no output file")
                continue
            if dst.read_bytes() != payload:
                got = len(dst.read_bytes())
                failures.append(f"{size}: got {got} bytes")
                continue

            # Also check liblzma accepts what MoonXZ writes, on a compressible
            # input, so the interop is verified in both directions.
            if size >= 1024:
                compressible = (b"MoonXZ boundary adapter payload.\n" * (size // 32 + 1))[:size]
                csrc = work / f"c{size}.bin"
                cxz = work / f"c{size}.xz"
                csrc.write_bytes(compressible)
                proc = subprocess.run(
                    ["moon", "run", "-q", "cmd/main", "--",
                     "compress-file", str(csrc), str(cxz), "crc64", "none"],
                    cwd=root, capture_output=True, text=True,
                    encoding="utf-8", errors="replace",
                )
                if proc.returncode == 0 and cxz.exists():
                    try:
                        if lzma.decompress(cxz.read_bytes()) != compressible:
                            failures.append(f"{size}: liblzma read our output wrong")
                    except lzma.LZMAError as exc:
                        failures.append(f"{size}: liblzma rejected our output ({exc})")

    if failures:
        print("boundary decode failed: " + "; ".join(failures), file=sys.stderr)
        return 1
    print(f"{len(SIZES)} liblzma sizes decoded exactly, both directions checked")
    return 0


if __name__ == "__main__":
    sys.exit(main())
